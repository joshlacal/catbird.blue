#!/usr/bin/env node
// Compiles design/tokens.json (the Catbird design system export, source of truth for
// this site) into src/styles/tokens.css. Dependency-free on purpose.
//
// Output shape (mirrors how the design system compiles its own previews):
//   :root, [data-theme="light"] { every color as --<name>, every shadow }
//   [data-theme="<id>"] { every color and shadow for that theme }   (dim, black, hc-*, cvd-*)
//   :root { spacing, radius, size, borderWidth, opacity, --font-<family> }
//   .t-<style> { font-family, font-size, line-height, font-weight }  (one per type style)
//
// Every theme block re-declares ALL color and shadow values, not just the differences,
// so a nested [data-theme] never inherits a value from the wrong theme.
// Aliases written as "{name}" compile to var(--name).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'design/tokens.json');
const out = resolve(root, 'src/styles/tokens.css');

const t = JSON.parse(readFileSync(src, 'utf8'));

const themeIds = t.color.themes.map((th) => th.id);
if (themeIds[0] !== 'light') {
  throw new Error(`Expected the first theme to be "light", got "${themeIds[0]}"`);
}

const alias = (value) =>
  typeof value === 'string' ? value.replace(/\{([a-z0-9-]+)\}/gi, 'var(--$1)') : String(value);

const valueFor = (token, themeId) => {
  const v = token.value;
  if (v !== null && typeof v === 'object') {
    if (!(themeId in v)) throw new Error(`Token ${token.name} has no value for theme ${themeId}`);
    return alias(v[themeId]);
  }
  return alias(v);
};

const decls = (tokens, themeId) =>
  tokens.map((tok) => `  --${tok.name}: ${valueFor(tok, themeId)};`).join('\n');

const themeBlock = (themeId) =>
  [
    `  /* color */`,
    decls(t.color.tokens, themeId),
    `  /* shadow */`,
    decls(t.shadow.tokens, themeId),
  ].join('\n');

const staticFamilies = ['spacing', 'radius', 'size', 'borderWidth', 'opacity'];

const lines = [];
lines.push(
  `/* GENERATED by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */`,
  `/* Source: ${t.meta?.repo ?? 'Catbird design system'} @ ${t.meta?.ref ?? 'unknown ref'} */`,
  ``,
  `:root, [data-theme="light"] {`,
  themeBlock('light'),
  `}`,
  ``,
);

for (const id of themeIds.slice(1)) {
  lines.push(`[data-theme="${id}"] {`, themeBlock(id), `}`, ``);
}

lines.push(`:root {`);
for (const fam of staticFamilies) {
  lines.push(`  /* ${fam} */`, decls(t[fam].tokens, 'light'));
}
lines.push(`  /* font families */`);
for (const [key, stack] of Object.entries(t.type.families)) {
  lines.push(`  --font-${key}: ${stack};`);
}
lines.push(`}`, ``);

lines.push(`/* type styles */`);
for (const group of t.type.groups) {
  for (const s of group.styles) {
    const expanded = group.family === 'expanded';
    lines.push(
      `.t-${s.name} {`,
      `  font-family: var(--font-${group.family});`,
      `  font-size: ${s.fontSize};`,
      `  line-height: ${s.lineHeight};`,
      `  font-weight: ${s.fontWeight};`,
      ...(expanded ? [`  font-stretch: 120%;`] : []),
      ...(s.name === 'count' ? [`  font-variant-numeric: tabular-nums;`] : []),
      `}`,
    );
  }
}
lines.push(``);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n'));
console.log(
  `tokens: wrote ${out.replace(root + '/', '')} (${t.color.tokens.length} colors x ${themeIds.length} themes, ${t.shadow.tokens.length} shadows)`,
);
